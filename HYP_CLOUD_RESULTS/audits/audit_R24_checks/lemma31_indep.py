#!/usr/bin/env python3
"""Referee R24: independent exact test of Lemma 3.1 (partial Wronskian divisor R_s).
Run: python3 -I lemma31_indep.py

Curves: C_m : y^2 + y = x^m over GF(2^8) (m odd), genus g=(m-1)/2, one point P_inf at infinity,
        ord_inf x=-2, ord_inf y=-m, div(dx)=(2g-2)P_inf, coordinate ring A=k[x]+k[x]y.
Linear systems V = span(xi_0..xi_r) inside L(k P_inf) = H^0(O(k P_inf)), tau=k.

For each V and each s:
  * orders eps_i computed EXACTLY in A (greedy: row_n of Hasse derivatives wrt x is new iff some
    minor with the previously chosen rows is a nonzero element of A);
  * the s x s minors w_J in A (exact);
  * affine part of deg R_s = dim_k A/(w_J)  (EXACT over the algebraic closure: A is Dedekind, so
    the ideal is locally m_P^{min_J ord_P w_J}); computed as deg gcd of 2x2 minors of the k[x]-module
    generated by w_J and y*w_J in k[x]^2;
  * v_inf(R_s) computed DIRECTLY from Laurent expansions at P_inf in a uniformizer t
    (frame t^{-k}), Hasse derivatives in t -- independent of the lemma's change-of-frame formula;
    also compared with the lemma's formula s*k+Sigma'(2g-2)-max_J pole(w_J);
  * check (a): deg R_s <= s*k + Sigma'(2g-2), equality for s=r+1 (SV Thm 1.5);
  * check (b) at EVERY affine GF(2^8)-point: v_P(R_s) (local Hasse minors in t=x-a) >= sum_{i<s}(j_i(P)-eps_i);
    also v_P(local) == min_J ord_P(w_J) (global minors), a consistency check of the D^(l)y recursion;
  * Thm 3.3 mechanism: for each non-order N with >=3 binary ones, the points P with N in j(P):
    v_P(R_s) >= N - max{eps<N} with s=#{eps<N}, and  #{such P} * gamma' <= deg R_s.
Exact failing sets are printed.
"""
from itertools import combinations, permutations

# ---------------- GF(2^8), modulus x^8+x^4+x^3+x^2+1 ----------------
MOD = 0x11D
EXP = [0] * 512
LOG = [0] * 256
v = 1
for i in range(255):
    EXP[i] = v
    LOG[v] = i
    v <<= 1
    if v & 0x100:
        v ^= MOD
for i in range(255, 512):
    EXP[i] = EXP[i - 255]
assert len(set(EXP[:255])) == 255

def mul(a, b):
    if a == 0 or b == 0:
        return 0
    return EXP[LOG[a] + LOG[b]]

def inv(a):
    return EXP[255 - LOG[a]]

def gpow(a, e):
    if e == 0:
        return 1
    if a == 0:
        return 0
    return EXP[(LOG[a] * e) % 255]

# ---------------- polynomials over GF(2^8): lists low->high ----------------
def trim(p):
    while p and p[-1] == 0:
        p.pop()
    return p

def padd(a, b):
    if len(a) < len(b):
        a, b = b, a
    r = a[:]
    for i, c in enumerate(b):
        r[i] ^= c
    return trim(r)

def pmul(a, b):
    if not a or not b:
        return []
    r = [0] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        if x == 0:
            continue
        lx = LOG[x]
        for j, y in enumerate(b):
            if y:
                r[i + j] ^= EXP[lx + LOG[y]]
    return trim(r)

def pscale(a, c):
    return trim([mul(c, x) for x in a])

def pdeg(a):
    return len(a) - 1  # -1 for zero

def pmod(a, b):
    a = a[:]
    db = pdeg(b)
    ib = inv(b[-1])
    while pdeg(a) >= db:
        c = mul(a[-1], ib)
        sh = pdeg(a) - db
        for i, y in enumerate(b):
            a[sh + i] ^= mul(c, y)
        trim(a)
    return a

def pgcd(a, b):
    a = trim(a[:]); b = trim(b[:])
    while b:
        a, b = b, pmod(a, b)
    if a:
        a = pscale(a, inv(a[-1]))
    return a

def binom2(n, k):  # C(n,k) mod 2 (Lucas)
    return 1 if (k & ~n) == 0 and 0 <= k <= n else 0

def phasse(p, n):
    if n == 0:
        return p[:]
    return trim([p[i] if binom2(i, n) else 0 for i in range(n, len(p))])

def ppow(p, e):
    r = [1]
    for _ in range(e):
        r = pmul(r, p)
    return r

def peval(p, a):
    s = 0
    for c in reversed(p):
        s = mul(s, a) ^ c
    return s

# ---------------- coordinate ring A = k[x] + k[x] y,  y^2 = y + p ----------------
class Curve:
    def __init__(self, m):
        self.m = m
        self.g = (m - 1) // 2
        self.p = [0] * m + [1]  # x^m
        self.cache = {}

    def Dy(self, l):  # D^(l) y in k[x] for l>=1
        if l in self.cache:
            return self.cache[l]
        r = phasse(self.p, l)
        if l % 2 == 0:
            h = self.Dy(l // 2)
            r = padd(r, pmul(h, h))
        self.cache[l] = r
        return r

    def amul(self, u, w):
        a, b = u; c, d = w
        bd = pmul(b, d)
        return (padd(pmul(a, c), pmul(bd, self.p)), padd(padd(pmul(a, d), pmul(b, c)), bd))

    def aadd(self, u, w):
        return (padd(u[0], w[0]), padd(u[1], w[1]))

    def ahasse(self, u, n):
        a, b = u
        ra = phasse(a, n)
        for l in range(1, n + 1):
            ra = padd(ra, pmul(phasse(b, n - l), self.Dy(l)))
        return (ra, phasse(b, n))

    def adet(self, M):
        n = len(M)
        tot = ([], [])
        for perm in permutations(range(n)):
            t = ([1], [])
            for i in range(n):
                t = self.amul(t, M[i][perm[i]])
                if not t[0] and not t[1]:
                    break
            tot = self.aadd(tot, t)
        return tot

    def pole(self, u):  # -ord_inf
        a, b = u
        cands = []
        if a:
            cands.append(2 * pdeg(a))
        if b:
            cands.append(2 * pdeg(b) + self.m)
        return max(cands) if cands else None

def iszeroA(u):
    return not u[0] and not u[1]

# ---------------- power series over GF(2^8) truncated at PR ----------------
def smul(a, b, PR):
    r = [0] * PR
    for i, x in enumerate(a[:PR]):
        if x == 0:
            continue
        lx = LOG[x]
        for j in range(min(len(b), PR - i)):
            y = b[j]
            if y:
                r[i + j] ^= EXP[lx + LOG[y]]
    return r

def sinv(a, PR):
    assert a[0] != 0
    r = [0] * PR
    i0 = inv(a[0])
    r[0] = i0
    for n in range(1, PR):
        s = 0
        for k in range(1, min(n, len(a) - 1) + 1):
            if a[k] and r[n - k]:
                s ^= mul(a[k], r[n - k])
        r[n] = mul(s, i0)
    return r

def spow(a, e, PR):
    r = [1] + [0] * (PR - 1)
    for _ in range(e):
        r = smul(r, a, PR)
    return r

def shasse(a, n, PR):
    return [a[i] if binom2(i, n) else 0 for i in range(n, PR)] + [0] * n

def sord(a):
    for i, c in enumerate(a):
        if c:
            return i
    return None  # zero to precision

def sdet(M, PR):
    n = len(M)
    tot = [0] * PR
    for perm in permutations(range(n)):
        t = [1] + [0] * (PR - 1)
        for i in range(n):
            t = smul(t, M[i][perm[i]], PR)
        tot = [x ^ y for x, y in zip(tot, t)]
    return tot

def vanishing_orders(series, PR):
    # echelon by leading order
    rows = [s[:] for s in series]
    js = []
    used = [False] * len(rows)
    for _ in range(len(rows)):
        best = None
        for idx, s in enumerate(rows):
            if used[idx]:
                continue
            o = sord(s)
            if o is None:
                continue
            if best is None or o < best[0]:
                best = (o, idx)
        if best is None:
            return None
        o, idx = best
        used[idx] = True
        js.append(o)
        piv = rows[idx]
        ip = inv(piv[o])
        for k2, s in enumerate(rows):
            if not used[k2] and s[o]:
                c = mul(s[o], ip)
                rows[k2] = [x ^ mul(c, y) for x, y in zip(s, piv)]
    return js

# ---------------- the test ----------------
def eval_A_series(u, xs, ys, PR):
    # u=(a,b) evaluated at power series x=xs, y=ys
    a, b = u
    def ev(p):
        r = [0] * PR
        pw = [1] + [0] * (PR - 1)
        for c in p:
            if c:
                r = [x ^ mul(c, y) for x, y in zip(r, pw)]
            pw = smul(pw, xs, PR)
        return r
    return [x ^ y for x, y in zip(ev(a), smul(ev(b), ys, PR))]

def run(curve, name, V, Ncands, PRaff=72):
    m, g = curve.m, curve.g
    k = max(curve.pole(u) for u in V)
    r1 = len(V)
    out = []
    out.append("== curve y^2+y=x^%d (g=%d), V=%s, tau=k=%d" % (m, g, name, k))
    # exact orders
    eps = []
    n = 0
    rowsA = {}
    def row(n):
        if n not in rowsA:
            rowsA[n] = [curve.ahasse(u, n) for u in V]
        return rowsA[n]
    while len(eps) < r1:
        cand = eps + [n]
        M = [row(e) for e in cand]
        new = False
        for J in combinations(range(r1), len(cand)):
            d = curve.adet([[M[i][j] for j in J] for i in range(len(cand))])
            if not iszeroA(d):
                new = True
                break
        if new:
            eps.append(n)
        n += 1
        assert n <= k + 1, "order search overflow"
    out.append("   exact orders eps = %s" % eps)
    # Laurent expansion at infinity: x=t^-2 X, y=t^-m X^{(m-1)/2}, X=1+t^m X^{-(m-1)/2}
    PRinf = 4 * k + 60
    X = [1] + [0] * (PRinf - 1)
    for _ in range(PRinf // m + 3):
        Xi = sinv(X, PRinf)
        Xp = spow(Xi, (m - 1) // 2, PRinf)
        X = [1] + [0] * (PRinf - 1)
        for i in range(PRinf - m):
            X[i + m] ^= Xp[i]
    # check curve equation: X^{m-1}(X+1) = t^m X^{(m-1)/2}
    lhs = smul(spow(X, m - 1, PRinf), [X[0] ^ 1] + X[1:], PRinf)
    rhs = [0] * m + spow(X, (m - 1) // 2, PRinf)[:PRinf - m]
    assert lhs == rhs
    Xpows = [[1] + [0] * (PRinf - 1)]
    for i in range(k + 1):
        Xpows.append(smul(Xpows[-1], X, PRinf))
    def at_inf(u):
        a, b = u
        s = [0] * PRinf
        for i, c in enumerate(a):
            if c:
                e = k - 2 * i
                assert e >= 0
                src = Xpows[i]
                for j in range(PRinf - e):
                    if src[j]:
                        s[j + e] ^= mul(c, src[j])
        for i, c in enumerate(b):
            if c:
                e = k - 2 * i - m
                assert e >= 0
                src = Xpows[i + (m - 1) // 2]
                for j in range(PRinf - e):
                    if src[j]:
                        s[j + e] ^= mul(c, src[j])
        return s
    yinf = [at_inf(u) for u in V]
    jinf = vanishing_orders(yinf, PRinf)
    # affine points
    roots = {}
    for b in range(256):
        roots.setdefault(mul(b, b) ^ b, []).append(b)
    pts = []
    for a in range(256):
        c = gpow(a, m)
        for b in roots.get(c, []):
            pts.append((a, b))
    loc = {}
    loc_xy = {}
    for (a, b) in pts:
        PR = PRaff
        xs = [a, 1] + [0] * (PR - 2)
        # q(t)=p(a+t)-p(a)
        q = [0] * PR
        for i in range(1, m + 1):
            if binom2(m, i):
                q[i] ^= gpow(a, m - i)
        Y = q[:]
        for _ in range(8):
            Y = [x ^ y for x, y in zip(q, smul(Y, Y, PR))]
        ys = [b] + Y[1:]
        ys[0] = b
        ser = [eval_A_series(u, xs, ys, PR) for u in V]
        loc[(a, b)] = (ser, vanishing_orders(ser, PR))
        loc_xy[(a, b)] = (xs, ys)
    allok = True
    for s in range(1, r1 + 1):
        Ms = [row(e) for e in eps[:s]]
        minors = []
        for J in combinations(range(r1), s):
            minors.append(curve.adet([[Ms[i][j] for j in J] for i in range(s)]))
        nz = [w for w in minors if not iszeroA(w)]
        # affine colength: module gens (a,b),(b p, a+b)
        gens = []
        for (a_, b_) in nz:
            gens.append((a_, b_))
            gens.append((pmul(b_, curve.p), padd(a_, b_)))
        G = []
        for i1 in range(len(gens)):
            for i2 in range(i1 + 1, len(gens)):
                dd = padd(pmul(gens[i1][0], gens[i2][1]), pmul(gens[i1][1], gens[i2][0]))
                G = pgcd(G, dd) if G else (pscale(dd, inv(dd[-1])) if dd else G)
        aff = pdeg(G)
        maxpole = max(curve.pole(w) for w in nz)
        sig = sum(eps[:s])
        # direct v_inf
        Minf = [[shasse(yinf[j], e, PRinf) for j in range(r1)] for e in eps[:s]]
        vinf = None
        for J in combinations(range(r1), s):
            d = sdet([[Minf[i][j] for j in J] for i in range(s)], PRinf)
            o = sord(d)
            if o is not None and (vinf is None or o < vinf):
                vinf = o
        vinf_formula = s * k + sig * (2 * g - 2) - maxpole
        degR = aff + vinf
        bound = s * k + sig * (2 * g - 2)
        okA = degR <= bound and (s < r1 or degR == bound) and vinf == vinf_formula
        allok &= okA
        out.append("   s=%d rows %s: deg R_s = affine %d + v_inf %d = %d; bound s*tau+Sigma'(2g-2) = %d; "
                   "v_inf(formula)=%d; (a) ok=%s%s"
                   % (s, eps[:s], aff, vinf, degR, bound, vinf_formula, okA,
                      " [equality required, s=r+1]" if s == r1 else ""))
        # (b) at all affine points + consistency
        fails = []
        incons = []
        wsum = 0
        for P, (ser, js) in loc.items():
            PR = PRaff
            Mloc = [[shasse(ser[j], e, PR) for j in range(r1)] for e in eps[:s]]
            vp = None
            for J in combinations(range(r1), s):
                d = sdet([[Mloc[i][j] for j in J] for i in range(s)], PR)
                o = sord(d)
                if o is not None and (vp is None or o < vp):
                    vp = o
            if vp is None:
                vp = PR  # >= PR
            need = sum(js[i] - eps[i] for i in range(s))
            if vp < need:
                fails.append((P, js, vp, need))
            # global minors (elements of A) expanded at P: must give the same v_P (t=x-a, frame 1)
            xs, ys = loc_xy[P]
            vg = min((sord(eval_A_series(w, xs, ys, PR)) if sord(eval_A_series(w, xs, ys, PR)) is not None else PR) for w in nz)
            if min(vg, PR) != min(vp, PR):
                incons.append((P, vp, vg))
            wsum += vp
        out.append("     (b) exact failing set over %d affine GF(2^8)-points: %s; sum of v_P over them = %d <= deg R_s: %s; local/global v_P inconsistencies: %s"
                   % (len(loc), fails, wsum, wsum <= degR, incons))
        allok &= (not fails) and wsum <= degR and not incons
    # Thm 3.3 mechanism
    for N in Ncands:
        if N in eps:
            continue
        below = [e for e in eps if e < N]
        s = len(below)
        gp = N - max(below)
        hits = [(P, js) for P, (ser, js) in loc.items() if N in js]
        if jinf and N in jinf:
            hits.append(("inf", jinf))
        out.append("   N=%d (non-order): s=%d, gamma'=%d, points with N in j(P): %s"
                   % (N, s, gp, [(P, js) for P, js in hits]))
        if hits:
            # recompute v_P(R_s) at hits (affine)
            bad = []
            vlist = []
            for P, js in hits:
                if P == "inf":
                    ser = yinf
                    PR = PRinf
                else:
                    ser = loc[P][0]
                    PR = PRaff
                Mloc = [[shasse(ser[j], e, PR) for j in range(r1)] for e in eps[:s]]
                vals = [sord(sdet([[Mloc[i][j] for j in J] for i in range(s)], PR)) for J in combinations(range(r1), s)]
                vp = min(PR if o is None else o for o in vals)
                vlist.append((P, vp))
                if vp < gp:
                    bad.append((P, js, vp))
            out.append("     v_P(R_s) at these points: %s; exact failing set for v_P(R_s)>=gamma': %s" % (vlist, bad))
            allok &= not bad
    out.append("   j(P_inf) = %s" % jinf)
    out.append("   ALL OK for this V: %s" % allok)
    return out, allok

def poly_xa_pow(a, e):
    return ppow([a, 1], e)

def main():
    total = True
    lines = []
    for m in (3, 5):
        C = Curve(m)
        # choose a with Tr(a^m)=0 so that the fibre x=a is rational (two points)
        roots = set(mul(b, b) ^ b for b in range(256))
        a = next(a for a in range(2, 256) if gpow(a, m) in roots)
        ya = None
        y = ([], [1])
        x = ([0, 1], [])
        one = ([1], [])
        systems = []
        systems.append(("span(1,x,(x-a)^7,x^8), a=%d" % a,
                        [one, x, (poly_xa_pow(a, 7), []), (ppow([0, 1], 8), [])]))
        systems.append(("span(1,x,(x-a)^7+y,x^8+x*y), a=%d" % a,
                        [one, x, (poly_xa_pow(a, 7), [1]), (ppow([0, 1], 8), [0, 1])]))
        y4 = C.amul(C.amul(y, y), C.amul(y, y))
        systems.append(("span(1,x,y^4,x*y^4)", [one, x, y4, C.amul(x, y4)]))
        systems.append(("span(1,x,(x-a)^14,x^16+y), a=%d" % a,
                        [one, x, (poly_xa_pow(a, 14), []), (ppow([0, 1], 16), [1])]))
        systems.append(("span(1,x,y,x^2)", [one, x, y, ([0, 0, 1], [])]))
        systems.append(("span(1,x,(x-a)^7) [dim 3]", [one, x, (poly_xa_pow(a, 7), [])]))
        for nm, V in systems:
            o, ok = run(C, nm, V, [7, 11, 13, 14, 19, 21, 22, 25, 26, 28])
            lines += o
            total &= ok
            print("\n".join(o), flush=True)
    print("OVERALL: all checks pass = %s" % total)

main()
